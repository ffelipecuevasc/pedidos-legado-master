/* Esquema base de datos PEDIDOS - DBISAM 4
   Generado con DBSYS 05/2008 */

CREATE TABLE IF NOT EXISTS "REGIONES"
(
   "COD_REGION" INTEGER NOT NULL,
   "NOMBRE" VARCHAR(40),
   "FLETE_BASE" MONEY,
PRIMARY KEY ("COD_REGION") COMPRESS NONE
LOCALE CODE 0
USER MAJOR VERSION 1
);

CREATE TABLE IF NOT EXISTS "CLIENTES"
(
   "ID_CLIENTE" AUTOINC,
   "RUT" VARCHAR(12) NOT NULL,
   "RAZON_SOCIAL" VARCHAR(60) NOT NULL,
   "DIRECCION" VARCHAR(80),
   "COMUNA" VARCHAR(40),
   "COD_REGION" INTEGER,
   "TIPO" CHAR(1) DEFAULT 'N',
   "TELEFONO" VARCHAR(20),
   "EMAIL" VARCHAR(60),
   "DEUDA_VENCIDA" MONEY DEFAULT 0,
   "FECHA_VENC_DEUDA" DATE,
   "ACTIVO" BOOLEAN DEFAULT TRUE,
   "FECHA_ALTA" DATE,
PRIMARY KEY ("ID_CLIENTE") COMPRESS NONE
LOCALE CODE 0
USER MAJOR VERSION 1
);

CREATE INDEX IF NOT EXISTS "IDX_RUT" ON "CLIENTES" ("RUT");
CREATE INDEX IF NOT EXISTS "IDX_RAZON" ON "CLIENTES" ("RAZON_SOCIAL");

CREATE TABLE IF NOT EXISTS "PRODUCTOS"
(
   "ID_PRODUCTO" AUTOINC,
   "CODIGO" VARCHAR(15) NOT NULL,
   "DESCRIPCION" VARCHAR(60),
   "CATEGORIA" CHAR(3),
   "PRECIO" MONEY,
   "STOCK" INTEGER DEFAULT 0,
   "STOCK_MINIMO" INTEGER DEFAULT 10,
   "UNIDAD" VARCHAR(5),
   "ACTIVO" BOOLEAN DEFAULT TRUE,
PRIMARY KEY ("ID_PRODUCTO") COMPRESS NONE
LOCALE CODE 0
USER MAJOR VERSION 1
);

CREATE UNIQUE INDEX IF NOT EXISTS "IDX_CODIGO" ON "PRODUCTOS" ("CODIGO");

/* ESTADO: P=pendiente C=confirmado A=anulado */
CREATE TABLE IF NOT EXISTS "PEDIDOS"
(
   "NRO_PEDIDO" INTEGER NOT NULL,
   "FECHA" DATE,
   "FECHA_INGRESO" TIMESTAMP,
   "ID_CLIENTE" INTEGER NOT NULL,
   "ESTADO" CHAR(1) DEFAULT 'P',
   "SUBTOTAL" MONEY,
   "DESCUENTO" MONEY,
   "FLETE" MONEY,
   "NETO" MONEY,
   "IVA" MONEY,
   "TOTAL" MONEY,
   "USUARIO" VARCHAR(20),
   "OBSERVACION" VARCHAR(250),
PRIMARY KEY ("NRO_PEDIDO") COMPRESS NONE
LOCALE CODE 0
USER MAJOR VERSION 1
);

CREATE INDEX IF NOT EXISTS "IDX_PED_FECHA" ON "PEDIDOS" ("FECHA");
CREATE INDEX IF NOT EXISTS "IDX_PED_CLIENTE" ON "PEDIDOS" ("ID_CLIENTE");

CREATE TABLE IF NOT EXISTS "PEDIDO_LINEAS"
(
   "NRO_PEDIDO" INTEGER NOT NULL,
   "LINEA" SMALLINT NOT NULL,
   "ID_PRODUCTO" INTEGER NOT NULL,
   "CANTIDAD" INTEGER,
   "PRECIO_UNIT" MONEY,
   "TOTAL_LINEA" MONEY,
PRIMARY KEY ("NRO_PEDIDO", "LINEA") COMPRESS NONE
LOCALE CODE 0
USER MAJOR VERSION 1
);

CREATE TABLE IF NOT EXISTS "PARAMETROS"
(
   "CLAVE" VARCHAR(30) NOT NULL,
   "VALOR" VARCHAR(60),
   "DESCRIPCION" VARCHAR(100),
PRIMARY KEY ("CLAVE") COMPRESS NONE
LOCALE CODE 0
USER MAJOR VERSION 1
);
